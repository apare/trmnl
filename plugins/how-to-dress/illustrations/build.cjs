// Generate the deployable Liquid from the same drawings the wardrobe preview uses.
const fs = require('node:fs');
const path = require('node:path');
const art = require('./wardrobe');
const clip = text => text.replaceAll('head-shape', '{{ head_id }}');
function cases(name, select) {
  return `{% template ${name} %}{% case key %}\n` + art.assets
    .filter(a => select(a))
    .map(a => `{% when '${a.id}' %}${select(a)}`)
    .join('\n') + '\n{% endcase %}{% endtemplate %}\n';
}
function build() {
  return `{% comment %}
  Generated by illustrations/build.cjs from illustrations/wardrobe.js.
  Drawings approved in the wardrobe preview, including the final snow-pants straps
  and the single front neck warmer. All pieces share the same coordinates.
  Change wardrobe.js, review illustrations/preview/, then regenerate this file.
{% endcomment %}
${cases('icon', a => a.art)}
${cases('clothing_front', a => a.front)}
${cases('clothing_back', a => a.back)}
${cases('clothing_head_front', a => a.headFront)}
{% template body %}${art.base}{% endtemplate %}
{% template bare_hands %}${art.bareHands}{% endtemplate %}
{% template bare_feet %}${art.bareFeet}{% endtemplate %}
{% template hair_back %}${art.hairBack}{% endtemplate %}
{% template head %}{% if character == 'long' %}${clip(art.head('long'))}{% else %}${clip(art.head('short'))}{% endif %}{% endtemplate %}

{% template mannequin %}
{% assign worn = pieces | map: 'key' %}
{% assign head_id = 'htd-head-' | append: uid | append: '-' | append: suffix %}
{% assign rain = false %}{% if worn contains 'impermeable' %}{% assign rain = true %}{% endif %}
<svg class="htd-mannequin {{ size }}" viewBox="${art.viewBox}" fill="none" stroke="#000" stroke-width="2.8" stroke-linejoin="round" stroke-linecap="round">
  <defs><clipPath id="{{ head_id }}">${art.hoodOpening ? `<path d="${art.hoodOpening}"/>` : ''}</clipPath></defs>
  {% if character == 'long' %}{% unless rain %}<g data-layer="hair-back">{% render 'hair_back' %}</g>{% endunless %}{% endif %}
  {% if worn contains 'hiver' %}<g data-side="back" data-item="hiver">{% render 'clothing_back', key: 'hiver' %}</g>
  {% elsif rain %}<g data-side="back" data-item="impermeable">{% render 'clothing_back', key: 'impermeable' %}</g>
  {% elsif worn contains 'misaison' %}
  {% elsif worn contains 'chandail' %}<g data-side="back" data-item="chandail">{% render 'clothing_back', key: 'chandail' %}</g>{% endif %}
  <g data-layer="body">{% render 'body' %}</g>
  {% for p in pieces %}{% unless p.key == 'casquette' or p.key == 'tuque' or p.key == 'cachecou' or p.key == 'gants' or p.key == 'mitaines' %}<g data-side="front" data-item="{{ p.key }}">{% render 'clothing_front', key: p.key %}</g>{% endunless %}{% endfor %}
  {% unless worn contains 'souliers' or worn contains 'bottesPluie' or worn contains 'bottesHiver' or worn contains 'collants' %}<g data-layer="bare-feet">{% render 'bare_feet' %}</g>{% endunless %}
  <g data-layer="face"{% if rain %} clip-path="url(#{{ head_id }})"{% endif %}>{% render 'head', character: character, head_id: head_id %}</g>
  <g{% if rain %} clip-path="url(#{{ head_id }})"{% endif %}>{% for p in pieces %}{% if p.key == 'casquette' or p.key == 'tuque' %}<g data-side="front" data-item="{{ p.key }}">{% render 'clothing_front', key: p.key %}</g>{% endif %}{% endfor %}</g>
  {% if rain %}<g data-side="headFront" data-item="impermeable">{% render 'clothing_head_front', key: 'impermeable' %}</g>{% endif %}
  {% if worn contains 'cachecou' %}<g data-side="front" data-item="cachecou">{% render 'clothing_front', key: 'cachecou' %}</g>{% endif %}
  {% if worn contains 'gants' %}<g data-side="front" data-item="gants">{% render 'clothing_front', key: 'gants' %}</g>
  {% elsif worn contains 'mitaines' %}<g data-side="front" data-item="mitaines">{% render 'clothing_front', key: 'mitaines' %}</g>
  {% else %}<g data-layer="bare-hands">{% render 'bare_hands' %}</g>{% endif %}
</svg>
{% endtemplate %}
`;
}
if (require.main === module) {
  const destination = path.join(__dirname, '../src/shared.liquid');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8') !== build()) {
      console.error('shared.liquid differs from the approved drawings. Run node illustrations/build.cjs.');
      process.exit(1);
    }
    console.log('Generated Liquid matches the illustration source.');
  } else {
    fs.writeFileSync(destination, build());
    console.log('Generated src/shared.liquid.');
  }
}
module.exports = { build };
